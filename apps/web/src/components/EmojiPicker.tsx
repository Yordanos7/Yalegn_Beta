export function EmojiPicker({ onEmojiSelect }: EmojiPickerProps) {
  const [isOpen, setIsOpen] = useState(false);
  const [selectedCategory, setSelectedCategory] = useState("Smileys & People");
  const pickerRef = useRef<HTMLDivElement>(null);

  // Close picker when clicking outside
  useEffect(() => {
    function handleClickOutside(event: MouseEvent) {
      if (
        pickerRef.current &&
        !pickerRef.current.contains(event.target as Node)
      ) {
        setIsOpen(false);
      }
    }

    if (isOpen) {
      document.addEventListener("mousedown", handleClickOutside);
    }

    return () => {
      document.removeEventListener("mousedown", handleClickOutside);
    };
  }, [isOpen]);

  const handleEmojiClick = (emoji: string) => {
    onEmojiSelect(emoji);
    // Don't close picker so user can select multiple emojis
  };

  return (
    <div className="relative" ref={pickerRef}>
      <Button
        type="button"
        variant="ghost"
        size="icon"
        onClick={() => setIsOpen(!isOpen)}
        className="hover:bg-accent"
        aria-label="Open emoji picker"
      >
        <Smile className="h-5 w-5 text-muted-foreground" />
      </Button>

      {isOpen && (
        <div className="absolute bottom-12 right-0 w-80 bg-card border border-border rounded-lg shadow-lg z-50">
          {/* Category tabs */}
          <div className="flex gap-1 p-2 border-b border-border overflow-x-auto">
            {Object.keys(emojiCategories).map((category) => (
              <button
                key={category}
                onClick={() => setSelectedCategory(category)}
                className={`px-3 py-1 text-xs rounded whitespace-nowrap transition-colors ${
                  selectedCategory === category
                    ? "bg-primary text-primary-foreground"
                    : "hover:bg-accent text-muted-foreground"
                }`}
              >
                {category.split(" ")[0]}
              </button>
            ))}
          </div>

          {/* Emoji grid */}
          <ScrollArea className="h-64 p-2">
            <div className="grid grid-cols-8 gap-1">
              {emojiCategories[
                selectedCategory as keyof typeof emojiCategories
              ].map((emoji, index) => (
                <button
                  key={`${emoji}-${index}`}
                  onClick={() => handleEmojiClick(emoji)}
                  className="text-2xl hover:bg-accent rounded p-1 transition-colors"
                  title={emoji}
                >
                  {emoji}
                </button>
              ))}
            </div>
          </ScrollArea>

          {/* Footer with frequently used (optional) */}
          <div className="p-2 border-t border-border text-xs text-muted-foreground text-center">
            Click emoji to insert
          </div>
        </div>
      )}
    </div>
  );
}
